# ---- 规则逻辑（与 reading-session.ts 对齐）----

_CRISIS_PATTERN = re.compile(r"自杀|自残|不想活|活不下去|结束生命|伤害自己|割腕", re.I)
_REGULATED_PATTERN = re.compile(r"诊断|吃什么药|病会好吗|能治好|股票|基金|买入|卖出|投资建议|官司|起诉|判刑|离婚协议", re.I)


def get_safety_concern(text: str):
    if _CRISIS_PATTERN.search(text):
        return "crisis"
    if _REGULATED_PATTERN.search(text):
        return "regulated"
    return None


def is_meaningful_question(text: str) -> bool:
    t = (text or "").strip()
    has_intent = re.search(r"是否|要不要|该不该|应该|应不应该|怎么办|如何|怎么|能不能|会不会|为什么|担心|选择|有没|关系|未来|发展", t)
    return len(t) >= 8 and bool(re.search(r"[\u4e00-\u9fffA-Za-z]", t)) and not re.fullmatch(r"\d+", t) and bool(has_intent)


def get_safety_message(concern: str) -> str:
    if concern == "crisis":
        return ("听起来你正在经历很难独自承受的时刻。这里不适合继续占卜，"
                "请优先联系身边信任的人、当地紧急服务或心理危机支持热线，确保自己此刻处于安全的环境中。")
    return ("塔罗可以帮助整理你对这件事的感受与顾虑，但不能替代医疗、法律或投资等专业判断。"
            "请将问题调整为“我目前最担心什么、下一步可以如何准备”，并向合格专业人士咨询。")


def recommend_spread(question: str, concern: str, goal: str) -> str:
    text = f"{question} {concern} {goal}"
    if re.search(r"选择|还是|要不要|是否|纠结|风险|取舍|计划|关系", text):
        return "three_cards"
    return "one_card"


def get_spread_reason(spread: str) -> str:
    if spread == "three_cards":
        return "你的问题包含选择或取舍。三张牌会帮助你看见现状、阻碍与可行动的方向。"
    return "你的问题较聚焦。单张牌适合先获得一个清晰的自我觉察方向。"


def draw_cards(spread: str):
    """随机抽取指定数量牌，返回 [(card_tuple, is_reversed), ...]"""
    count = SPREADS[spread]["card_count"]
    pool = list(TAROT_CARDS)
    random.shuffle(pool)
    drawn = pool[:count]
    return [(c, random.random() < 0.5) for c in drawn]


def shuffled_deck():
    """返回洗好的整副 78 张牌 [(card_tuple, is_reversed), ...]，供用户自行点击选取。"""
    pool = list(TAROT_CARDS)
    random.shuffle(pool)
    return [(c, random.random() < 0.5) for c in pool]

